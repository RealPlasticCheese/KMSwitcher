test('a megabyte upload survives lost acknowledgements at twenty percent without duplicate writes', async t => {
  const image = Uint8Array.from({ length: 1024 * 1024 }, (_, i) => i % 256);
  const flashed = new Uint8Array(image.length);
  const failureOffset = Math.floor(image.length / 5 / 188) * 188;
  let written = 0, dropped = 0;
  const port = new Port((command, serial) => {
    const request = decodeFrame(unhex(command.split(' ')[2])), chunk = request.data.subarray(4);
    if (request.offset === written) { flashed.set(chunk, written); written += chunk.length; }
    else assert.deepEqual(flashed.subarray(request.offset, request.offset + chunk.length), chunk);
    if (request.offset === failureOffset && dropped++ < 5) return;
    serial.emit(line(reply(command, { data: words(written) })));
  });
  const connection = await connected(t, port), controller = new Controller(connection, { timeout: 20 });
  for (let offset = 0; offset < image.length; offset += 188) {
    const chunk = image.subarray(offset, offset + 188), data = new Uint8Array(4 + chunk.length);
    data.set(words(123)); data.set(chunk, 4);
    assert.equal(word((await controller.request(2, OP.WRITE, data, { offset })).data), offset + chunk.length);
  }
  assert.deepEqual(flashed, image);
  assert.equal(dropped, 6);
});

