class UpdateController {
  constructor(sample, { current = false, failEnd = false, rollback = false, neverReboot = false, disconnect = false } = {}) {
    Object.assign(this, { sample, current, failEnd, rollback, neverReboot, disconnect });
    this.connection = { connected: true }; this.ops = []; this.routes = []; this.activated = false;
    this.time = 0; this.identities = 0; this.size = 0;
  }
  async identity() {
    this.identities++;
    const rebooted = this.activated && !this.neverReboot;
    return { chip: 2, capabilities: 7, confirmed: true, boot: rebooted ? 2 : 1,
      sha256: this.current || (rebooted && !this.rollback) ? this.sample.metadata.sha256 : 'bb'.repeat(32) };
  }
  async route(paused) { this.routes.push(paused); }
  async request(slot, op, data, options = {}) {
    this.ops.push(op);
    if (op === OP.BEGIN) return { status: 0, data: words(0) };
    if (op === OP.WRITE) { assert.equal(options.offset, this.size); this.size += data.length - 4; return { data: words(this.size) }; }
    if (op === OP.END && this.failEnd) throw new ManagementError(STATUS.INTEGRITY);
    if (op === OP.ACTIVATE) { this.activated = true; if (this.disconnect) this.connection.connected = false; }
    return { data: new Uint8Array() };
  }
  options() { return { sleep: async ms => { this.time += ms; }, now: () => this.time }; }
}
