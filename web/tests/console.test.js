class Port {
  constructor(handler = () => {}) { this.handler = handler; this.commands = []; }
  async open(options) {
    this.options = options;
    this.readable = new ReadableStream({ start: output => { this.output = output; } });
    this.writable = new WritableStream({ write: bytes => {
      const command = new TextDecoder().decode(bytes).trim(); this.commands.push(command); this.handler(command, this);
    } });
  }
  async setSignals(signals) { this.signals = signals; }
  emit(text) { this.output.enqueue(new TextEncoder().encode(text)); }
  async close() { this.closed = true; }
}
function reply(command, changes = {}) {
  const frame = decodeFrame(unhex(command.split(' ')[2]));
  return { ...frame, sender: frame.target || 22, target: 11, flags: 1, data: new Uint8Array(), ...changes };
}
const line = frame => `KMSM ${frame.slot} ${hex(encodeFrame(frame))}\n`;
async function connected(t, port, options) {
  const connection = new SerialConnection(options); await connection.open(port);
  t.after(() => connection.close()); return connection;
}

